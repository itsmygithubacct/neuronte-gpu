#!/usr/bin/env python3
"""Write a C file that embeds the compiled kernels.

    embed.py OUT.c --ptx H=FILE ... --spirv EXACT=FILE ...

PTX is embedded as bytes (the backend adds the terminating NUL); SPIR-V as
32-bit words. Either list may be empty: the matching backend then reports
that no kernel was built.
"""

import argparse
from pathlib import Path


def byte_rows(data, width=16):
    for i in range(0, len(data), width):
        yield ", ".join(str(b) for b in data[i:i + width])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("out")
    ap.add_argument("--ptx", nargs="*", default=[])
    ap.add_argument("--spirv", nargs="*", default=[])
    args = ap.parse_args()

    lines = ["/* Generated by tools/embed.py. Do not edit. */", '#include "internal.h"', ""]
    ptx = []
    for item in args.ptx:
        h, path = item.split("=", 1)
        data = Path(path).read_bytes()
        name = f"ptx_h{int(h)}"
        lines.append(f"static const unsigned char {name}[] = {{")
        lines.extend(f"    {row}," for row in byte_rows(data))
        lines.append("};")
        ptx.append((int(h), name))
    spirv = []
    for item in args.spirv:
        exact, path = item.split("=", 1)
        data = Path(path).read_bytes()
        if len(data) % 4 or int.from_bytes(data[:4], "little") != 0x07230203:
            raise SystemExit(f"{path}: not SPIR-V")
        words = [int.from_bytes(data[i:i + 4], "little") for i in range(0, len(data), 4)]
        name = f"spirv_exact{int(exact)}"
        lines.append(f"static const uint32_t {name}[] = {{")
        for i in range(0, len(words), 8):
            lines.append("    " + ", ".join(f"0x{w:08x}u" for w in words[i:i + 8]) + ",")
        lines.append("};")
        spirv.append((int(exact), name, len(words)))

    lines.append("const struct embedded_ptx neuronte_gpu_ptx[] = {")
    lines.extend(f"    {{{h}, {name}, sizeof {name}}}," for h, name in ptx)
    lines.append("    {0, 0, 0},")
    lines.append("};")
    lines.append(f"const int neuronte_gpu_ptx_count = {len(ptx)};")
    lines.append("const struct embedded_spirv neuronte_gpu_spirv[] = {")
    lines.extend(f"    {{{exact}, {name}, {words}}}," for exact, name, words in spirv)
    lines.append("    {0, 0, 0},")
    lines.append("};")
    lines.append(f"const int neuronte_gpu_spirv_count = {len(spirv)};")
    Path(args.out).write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
